export const getRelatedBlogPosts = (slug, limit = 3) => {
  const currentPost = getBlogPostBySlug(slug);
  return blogPosts
    .filter((post) => post.slug !== currentPost?.slug)
    .filter((post) => !currentPost || post.category === currentPost.category || post.tags.some((tag) => currentPost.tags.includes(tag)))
    .concat(blogPosts.filter((post) => post.slug !== currentPost?.slug))
    .filter((post, index, posts) => posts.findIndex((item) => item.slug === post.slug) === index)
    .slice(0, limit);
};
