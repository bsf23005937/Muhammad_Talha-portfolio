export const getProjectBySlug = (slug) => portfolioProjects.find((project) => project.slug === slug || String(project.id) === String(slug));

export const getRelatedProjects = (slug, limit = 3) => {
  const currentProject = getProjectBySlug(slug);
  return portfolioProjects
    .filter((project) => project.slug !== currentProject?.slug)
    .slice(0, limit);
};
